// TradeTrackerCore.VERSION is generated from VERSION_NAME, not hand-written. It used to be a `const` with a
// "keep in sync with gradle.properties" comment, and nobody kept it: every release through 1.0.3-beta
// reported `0.1.0-SNAPSHOT` to the host and on the heartbeat. A value that has to be remembered is a value
// that drifts, so the build writes it. Snapshots get VERSION_NAME itself (`x.y.z-SNAPSHOT`), not the npm
// `-SNAPSHOT.<n>`: that suffix is computed after the build, by core/npm/prepare-package.sh.
val generateCoreVersion by tasks.registering {
    group = "build"
    description = "Writes CoreBuildInfo.kt carrying VERSION_NAME from gradle.properties."
    val version = providers.gradleProperty("VERSION_NAME")
    val outDir = layout.buildDirectory.dir("generated/coreVersion/commonMain/kotlin")
    inputs.property("version", version)
    outputs.dir(outDir)
    doLast {
        val value = version.get()
        require(value.isNotBlank()) { "VERSION_NAME is blank in gradle.properties" }
        val file = outDir.get().file("com/dmarket/p2p/tracker/runtime/CoreBuildInfo.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |// Generated by :core:generateCoreVersion from VERSION_NAME in gradle.properties. Do not edit.
            |package com.dmarket.p2p.tracker.runtime
            |
            |internal object CoreBuildInfo {
            |    const val VERSION: String = "$value"
            |}
            |
            """.trimMargin(),
        )
    }
}

kotlin.sourceSets.commonMain {
    kotlin.srcDir(generateCoreVersion)
}

