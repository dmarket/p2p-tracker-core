// TradeTrackerCore.VERSION is generated from VERSION_NAME, not hand-written. It used to be a `const` with a
// "keep in sync with gradle.properties" comment, and nobody kept it: every release through 1.0.3-beta
// reported `0.1.0-SNAPSHOT` to the host and on the heartbeat. A value that has to be remembered is a value
// that drifts, so the build writes it. Snapshots get VERSION_NAME itself (`x.y.z-SNAPSHOT`), not the npm
// `-SNAPSHOT.<n>`: that suffix is computed after the build, by core/npm/prepare-package.sh.
val generateCoreVersion by tasks.registering {
    group = "build"
    description = "Writes CoreBuildInfo.kt carrying VERSION_NAME from gradle.properties."
    val version = providers.gradleProperty("VERSION_NAME")
    val outDir = layout.buildDirectory.dir("generated/coreVersion/commonMain/kotlin")
    inputs.property("version", version)
    outputs.dir(outDir)
    doLast {
        val value = version.get()
        require(value.isNotBlank()) { "VERSION_NAME is blank in gradle.properties" }
        val file = outDir.get().file("com/dmarket/p2p/tracker/runtime/CoreBuildInfo.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |// Generated by :core:generateCoreVersion from VERSION_NAME in gradle.properties. Do not edit.
            |package com.dmarket.p2p.tracker.runtime
            |
            |internal object CoreBuildInfo {
            |    const val VERSION: String = "$value"
            |}
            |
            """.trimMargin(),
        )
    }
}

kotlin.sourceSets.commonMain {
    kotlin.srcDir(generateCoreVersion)
}

// CoreVersionTest compares the generated constant against the property itself, which is what catches the
// generation silently falling back to something else.
tasks.withType<Test>().configureEach {
    systemProperty("dmarket.versionName", providers.gradleProperty("VERSION_NAME").get())
}

// The library output uses ES modules (useEsModules() above), but the Mocha / Node test runner
// needs CommonJS so that require() and __dirname are available in jsTest/Fixtures.kt.
//
// useEsModules() does two things for each compilation:
//   1. Sets compilation.compilerOptions.options.moduleKind = MODULE_ES
//      → this drives KotlinJsCompilation.fileExtension → determines the expected ".mjs" / ".js"
//        suffix in JsIrBinary.mainFileSyncPath (what jsNodeTest.onlyIf checks for existence).
//   2. Sets each binary's linkTask.compilerOptions.moduleKind = MODULE_ES
//      → this drives the actual file extension the Kotlin compiler writes out.
//
// We need to override BOTH for the test compilation so that the expected path and the produced
// file both use ".js" (CJS).  Two separate hooks are needed because (1) and (2) live on
// different objects.
kotlin {
    js {
        // Override (1): test compilation's own compilerOptions.  The suppression is intentional —
        // the deprecated accessor is the only one that drives KotlinJsCompilation.fileExtension.
        compilations.named("test") {
            @Suppress("DEPRECATION")
            compilerOptions.options.moduleKind.set(JsModuleKind.MODULE_COMMONJS)
        }
    }
}

// Override (2): the link task that produces the final test bundle.
tasks.withType<org.jetbrains.kotlin.gradle.targets.js.ir.KotlinJsIrLink>()
    .matching { it.name == "compileTestDevelopmentExecutableKotlinJs" }
    .configureEach {
        compilerOptions {
            moduleKind.set(JsModuleKind.MODULE_COMMONJS)
        }
    }

// The TLSN prover travels WITH the library. notary/WasmProverModule.kt import()s `pkg/client_wasm.js` and
// `transport/dist/index.js` from the extension root (runtime.getURL), and the extension puts them there by
// copying both directories out of this package — so they must sit at the root of the distribution, and
// therefore of the published tarball, which ships the whole productionLibrary dir. Without copyTlsnProver the
// notary path resolves to nothing.
//
// The source is the pinned npm package (TlsnProverPin), as installed by the Kotlin/JS npm install. Exactly three
// paths are taken (TlsnProverPin.SHIPPED: pkg/, transport/, VERSION) — the same three the tarball carried when the
// prover was committed to this repo, so the layout the extension depends on does not move. :headless-js copies the
// same three into its own distribution, after this task's check. VERSION rides along so a shipped build can
// be traced to the upstream commit (GIT_SHA) and the notary it must match. Everything else in the package
// stays behind: its package.json, README.md, CHANGELOG.md, LICENSE and THIRD_PARTY_NOTICES.md would collide
// with ours or describe the wrong package, and SHA256SUMS also covers that README, so a `-c` run over the
// copy would report a spurious miss.
//
// verifyTlsnProver checks the installed package; any miss fails the build. CI runs no separate step, and
// nothing reads the package before this task has passed — not copyTlsnProver, and not the JS tests either,
// which load and run the real pkg/ (WasmRevealPolicyContractTest). The tests are the part that is easy to
// miss: CI runs `check` before the distribution task, so without the edge below a substituted package would
// execute in the CI job before the check that rejects it.
//   1. the lockfile entry the install used carries TlsnProverPin.INTEGRITY — ties the whole npm tarball to a
//      value committed here, so the bytes installed today are the bytes that were pinned;
//   2. the installed package.json is TlsnProverPin.VERSION, and its gitHead equals VERSION's GIT_SHA;
//   3. the files we ship are exactly the pkg/, transport/ and VERSION entries of the package's SHA256SUMS,
//      and each matches it — an unlisted file fails, and so does a listed one that is missing;
//   4. VERSION's WASM_SHA256 is the digest of the .wasm actually installed.
// 2-4 check the package against itself and catch a damaged or half-replaced install; only 1 checks it
// against this repository.
val verifyTlsnProver by tasks.registering(VerifyTlsnProver::class) {
    group = "verification"
    description = "Verifies the installed TLSN prover npm package against TlsnProverPin."
    val npm = kotlin.js().compilations.getByName("main").npmProject
    dependsOn(npm.nodeJsRoot.npmInstallTaskProvider)
    // Copied into locals: the lambdas below must not capture this script, or the task cannot be stored in
    // the configuration cache.
    val name = TlsnProverPin.PACKAGE
    packageName.set(name)
    packageVersion.set(TlsnProverPin.VERSION)
    packageIntegrity.set(TlsnProverPin.INTEGRITY)
    packageDir.set(npm.nodeModulesDir.map { it.dir(name) })
    installLock.set(npm.nodeJsRoot.rootPackageDirectory.map { it.file("yarn.lock") })
    stamp.set(layout.buildDirectory.file("tlsn-prover/verified.txt"))
}

tasks.withType<KotlinJsTest>().configureEach { dependsOn(verifyTlsnProver) }

val copyTlsnProver by tasks.registering(Copy::class) {
    group = "build"
    description = "Copies the verified TLSN prover's pkg/ + transport/ + VERSION into the JS library distribution."
    dependsOn(verifyTlsnProver)
    from(verifyTlsnProver.flatMap { it.packageDir }) {
        include(TlsnProverPin.SHIPPED)
    }
    into(layout.buildDirectory.dir("dist/js/productionLibrary"))
}

tasks.named("jsBrowserProductionLibraryDistribution") { finalizedBy(copyTlsnProver) }
